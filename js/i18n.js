  function normalizeLanguage(value) {
    const base = String(value || '').toLowerCase().split(/[-_]/)[0];
    return SUPPORTED.includes(base) ? base : null;
  }

  function readSettings() {
    try {
      return JSON.parse(localStorage.getItem(STORAGE_KEY)) || {};
    } catch (error) {
      return {};
    }
  }

  function detectLanguage() {
    const saved = normalizeLanguage(readSettings().language);
    if (saved) return saved;

    const preferred = [navigator.language]
      .concat(Array.isArray(navigator.languages) ? navigator.languages : [])
      .filter(Boolean);

    for (let index = 0; index < preferred.length; index += 1) {
      const supported = normalizeLanguage(preferred[index]);
      if (supported) return supported;
    }

    return DEFAULT_LANGUAGE;
  }

  let current = detectLanguage();

  function t(key, params) {
    const table = MESSAGES[current] || MESSAGES[DEFAULT_LANGUAGE];
    let value = table[key];

    if (value == null) {
      value = MESSAGES[DEFAULT_LANGUAGE][key];
    }

    if (value == null) return key;

    if (params) {
      value = value.replace(/\{(\w+)\}/g, function (match, name) {
        return params[name] == null ? '' : String(params[name]);
      });
    }

    return value;
  }

  function translateError(message) {
    const key = SERVER_ERROR_KEYS[String(message || '').trim()];
    return key ? t(key) : message;
  }

  function apply(root) {
    const scope = root && typeof root.querySelectorAll === 'function' ? root : document;
    const language = current;

    scope.querySelectorAll('[data-i18n]').forEach(function (element) {
      const key = element.getAttribute('data-i18n');
      const value = t(key);
      if (value !== key) element.textContent = value;
    });

    scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (element) {
      const key = element.getAttribute('data-i18n-placeholder');
      const value = t(key);
      if (value !== key) element.setAttribute('placeholder', value);
    });

    scope.querySelectorAll('[data-i18n-title]').forEach(function (element) {
      const key = element.getAttribute('data-i18n-title');
      const value = t(key);
      if (value !== key) element.setAttribute('title', value);
    });

    scope.querySelectorAll('[data-i18n-aria-label]').forEach(function (element) {
      const key = element.getAttribute('data-i18n-aria-label');
      const value = t(key);
      if (value !== key) element.setAttribute('aria-label', value);
    });

    document.documentElement.lang = language;
  }

  function persistLanguage(language) {
    try {
      const settings = readSettings();
      settings.language = language;
      localStorage.setItem(STORAGE_KEY, JSON.stringify(settings));
    } catch (error) {
      /* armazenamento indisponível */
    }
  }

  function setLanguage(language, options) {
    const next = normalizeLanguage(language) || DEFAULT_LANGUAGE;
    current = next;

    if (!options || options.persist !== false) {
      persistLanguage(next);
    }

    apply();
    window.dispatchEvent(
      new CustomEvent('stop:languagechange', { detail: { language: next } })
    );
    return next;
  }

  function categoryName(category) {
    return t('category.' + category);
  }

  window.I18N = {
    supported: SUPPORTED.slice(),
    detectLanguage: detectLanguage,
    getLanguage: function () {
      return current;
    },
    setLanguage: setLanguage,
    apply: apply,
    t: t,
    categoryName: categoryName,
    translateError: translateError
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () {
      apply();
    });
  } else {
    apply();
  }
